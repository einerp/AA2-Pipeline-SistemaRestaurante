-- Mesa Lista: esquema académico para catálogo, inventario y facturación POS.
-- Ejecutar completo en Supabase SQL Editor. Todas las tablas aplican RLS por usuario.

create extension if not exists pgcrypto;

create table if not exists public.categorias (
  id uuid primary key default gen_random_uuid(),
  usuario_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  nombre text not null check (char_length(nombre) between 2 and 60),
  descripcion text check (descripcion is null or char_length(descripcion) <= 180),
  creado_en timestamptz not null default now(),
  unique (usuario_id, nombre)
);

create table if not exists public.productos (
  id uuid primary key default gen_random_uuid(),
  usuario_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  categoria_id uuid not null references public.categorias(id) on delete restrict,
  nombre text not null check (char_length(nombre) between 2 and 90),
  sku text not null check (char_length(sku) between 1 and 30),
  precio numeric(12,2) not null check (precio >= 0),
  stock integer not null default 0 check (stock >= 0),
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  unique (usuario_id, sku)
);

create table if not exists public.facturas (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  usuario_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  cliente_nombre text not null check (char_length(cliente_nombre) between 2 and 100),
  cliente_documento text not null default '222222222222',
  subtotal numeric(12,2) not null check (subtotal >= 0),
  impuesto numeric(12,2) not null check (impuesto >= 0),
  total numeric(12,2) not null check (total >= 0),
  creado_en timestamptz not null default now()
);

create table if not exists public.detalle_factura (
  id uuid primary key default gen_random_uuid(),
  usuario_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  factura_id uuid not null references public.facturas(id) on delete cascade,
  producto_id uuid references public.productos(id) on delete set null,
  producto_nombre text not null,
  cantidad integer not null check (cantidad > 0),
  precio_unitario numeric(12,2) not null check (precio_unitario >= 0),
  subtotal numeric(12,2) not null check (subtotal >= 0)
);

create index if not exists categorias_usuario_idx on public.categorias (usuario_id);
create index if not exists productos_usuario_categoria_idx on public.productos (usuario_id, categoria_id);
create index if not exists facturas_usuario_fecha_idx on public.facturas (usuario_id, creado_en desc);
create index if not exists detalle_factura_idx on public.detalle_factura (factura_id);

alter table public.categorias enable row level security;
alter table public.productos enable row level security;
alter table public.facturas enable row level security;
alter table public.detalle_factura enable row level security;

create policy "Cada usuario gestiona sus categorias" on public.categorias
  for all to authenticated using ((select auth.uid()) = usuario_id)
  with check ((select auth.uid()) = usuario_id);
create policy "Cada usuario gestiona sus productos" on public.productos
  for all to authenticated using ((select auth.uid()) = usuario_id)
  with check ((select auth.uid()) = usuario_id);
create policy "Cada usuario consulta sus facturas" on public.facturas
  for all to authenticated using ((select auth.uid()) = usuario_id)
  with check ((select auth.uid()) = usuario_id);
create policy "Cada usuario consulta su detalle" on public.detalle_factura
  for all to authenticated using ((select auth.uid()) = usuario_id)
  with check ((select auth.uid()) = usuario_id);

-- Privilegios mínimos para el rol autenticado; RLS sigue limitando cada fila.
grant usage on schema public to authenticated;
grant select, insert, update, delete on table public.categorias, public.productos, public.facturas, public.detalle_factura to authenticated;

-- La función valida propiedad e inventario, calcula valores en el servidor,
-- inserta cabecera y detalle, y descuenta existencias en una sola transacción.
create or replace function public.crear_factura(
  p_cliente_nombre text,
  p_cliente_documento text default '222222222222',
  p_items jsonb default '[]'::jsonb
) returns public.facturas
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_factura public.facturas;
  v_item jsonb;
  v_producto public.productos;
  v_cantidad integer;
  v_subtotal numeric(12,2) := 0;
  v_impuesto numeric(12,2) := 0;
begin
  if auth.uid() is null then
    raise exception 'Debe iniciar sesión para facturar';
  end if;
  if p_cliente_nombre is null or char_length(trim(p_cliente_nombre)) < 2 then
    raise exception 'El nombre del cliente es obligatorio';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 50 then
    raise exception 'La factura debe contener entre 1 y 50 renglones';
  end if;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_cantidad := (v_item->>'cantidad')::integer;
    if v_cantidad < 1 or v_cantidad > 100 then
      raise exception 'La cantidad debe estar entre 1 y 100';
    end if;
    select * into v_producto from public.productos
      where id = (v_item->>'producto_id')::uuid
        and usuario_id = auth.uid() and activo = true
      for update;
    if not found then raise exception 'Producto no disponible'; end if;
    if v_producto.stock < v_cantidad then
      raise exception 'Inventario insuficiente para %', v_producto.nombre;
    end if;
    v_subtotal := v_subtotal + round(v_producto.precio * v_cantidad, 2);
  end loop;

  v_impuesto := round(v_subtotal * 0.08, 2);
  insert into public.facturas (cliente_nombre, cliente_documento, subtotal, impuesto, total)
  values (trim(p_cliente_nombre), coalesce(nullif(trim(p_cliente_documento), ''), '222222222222'), v_subtotal, v_impuesto, v_subtotal + v_impuesto)
  returning * into v_factura;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_cantidad := (v_item->>'cantidad')::integer;
    select * into v_producto from public.productos where id = (v_item->>'producto_id')::uuid;
    insert into public.detalle_factura (factura_id, producto_id, producto_nombre, cantidad, precio_unitario, subtotal)
    values (v_factura.id, v_producto.id, v_producto.nombre, v_cantidad, v_producto.precio, round(v_producto.precio * v_cantidad, 2));
    update public.productos set stock = stock - v_cantidad where id = v_producto.id;
  end loop;

  return v_factura;
end;
$$;

grant execute on function public.crear_factura(text, text, jsonb) to authenticated;
