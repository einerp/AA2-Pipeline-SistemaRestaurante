-- Esquema inicial del Sistema de Gestión de Restaurante.
create table if not exists public.reservas (
    id bigint generated by default as identity primary key,
    cliente text not null,
    correo text not null,
    fecha date not null,
    hora text not null,
    personas integer not null check (personas between 1 and 8),
    mesa integer not null check (mesa between 1 and 8),
    estado text not null default 'confirmada',
    creado_en timestamptz not null default now(),
    unique (mesa, fecha, hora)
);

create table if not exists public.pedidos (
    id bigint generated by default as identity primary key,
    cliente text not null,
    tipo text not null check (tipo in ('recoger', 'domicilio')),
    platos jsonb not null,
    total integer not null check (total >= 0),
    estado text not null default 'recibido',
    creado_en timestamptz not null default now()
);

create index if not exists reservas_fecha_hora_idx on public.reservas (fecha, hora);
create index if not exists pedidos_creado_en_idx on public.pedidos (creado_en desc);

alter table public.reservas enable row level security;
alter table public.pedidos enable row level security;

